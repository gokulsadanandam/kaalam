    /** "வியாழன் · 12 நவம்பர் 2026" / "Thursday, 12 Nov 2026" */
    fun fullDate(date: LocalDate): String =
        dateFormat(weekday(date.dayOfWeek), date.dayOfMonth, months[date.monthValue - 1], date.year)

    fun weekday(day: DayOfWeek): String = weekdays[day.value % 7] // Sunday = 0

    /** "நவம்பர்" / "Nov" */
    fun monthName(month: Int): String = months[month - 1]

    /** "1 ம 25 நி" / "1h 25m"; minutes only below an hour. */
    fun duration(minutes: Int): String {
        val h = minutes / 60
        val m = minutes % 60
        return if (h > 0) "$h$hourUnit $m$minuteUnit" else "$m$minuteUnit"
    }

    fun periodName(type: PeriodType): String = when (type) {
        PeriodType.RAHU_KALAM -> rahuKalam
        PeriodType.YAMAGANDAM -> yamagandam
        PeriodType.KULIGAI -> kuligai
        PeriodType.NALLA_NERAM -> nallaNeram
        PeriodType.ABHIJIT -> nallaNeram
    }
}

