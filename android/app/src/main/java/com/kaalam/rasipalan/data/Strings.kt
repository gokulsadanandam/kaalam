/** In-app display language. Independent of the phone's system language. */
enum class AppLanguage(val code: String) {
    TAMIL("ta"),
    ENGLISH("en");

    companion object {
        val DEFAULT = TAMIL

        fun fromCode(code: String?): AppLanguage = entries.firstOrNull { it.code == code } ?: DEFAULT
    }
}

