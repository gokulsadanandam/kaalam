#!/usr/bin/env node
/**
 * Calendar-sheet vocabulary tools (source 'tamildailycalendar').
 *
 *   node scripts/maha-vocabulary.js --fix [--dry-run]
 *       Spelling cleanup: a rare word (seen ≤ 3 times) that differs from a
 *       common word (seen ≥ 30 times) only by a pulli or a doubled consonant
 *       is a misread of it ("ஆதாயம" -> "ஆதாயம்", "எதிர்பு" -> "எதிர்ப்பு");
 *       rewrite it in the archive. Vowel signs and letters are never changed
 *       (நாசம் ≠ நேசம், குறைவு ≠ நிறைவு).
 *
 *   node scripts/maha-vocabulary.js --translate [--dry-run]
 *       English for every sheet word that has none yet, via Gemini 2.5 Flash
 *       on Replicate (text only, about a cent for the whole vocabulary).
 *       Writes lib/mahaWordsEn.js; existing entries (and hand edits) are kept.
 */
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { BACKEND_DIR, connect, parseArgs } from './lib/common.js';
import { clusters, editDistance } from './lib/maha-read.js';

const SOURCE = 'tamildailycalendar';
const DICTIONARY = path.join(BACKEND_DIR, 'lib', 'mahaWordsEn.js');

async function wordCounts(db) {
  const { rows } = await db.query(
    'select word, count(*)::int as n from public.rasipalan_archive where source = $1 and word is not null group by 1 order by 2 desc',
    [SOURCE],
  );
  return rows;
}

/** The word without pulli (்): a missing or extra pulli is the commonest misread and never changes the word. */
const baseLetters = (word) => word.replace(/\u0BCD/gu, '');

/**
 * Is [rare] a misread of [common] that cannot change the meaning? Only a
 * pulli differs ("ஆதாயம" for "ஆதாயம்", "ஓயவு" for "ஓய்வு"), or a consonant
 * is doubled or undoubled ("எதிர்பு", "உற்ச்சாகம்", "சேர்கை"). Vowel signs
 * are never touched: நாசம் / நேசம், களைப்பு / களிப்பு, சோகம் / சுகம் are
 * different, even opposite, words.
 */
function isSafeMisread(rare, common) {
  const a = baseLetters(rare);
  const b = baseLetters(common);
  if (a === b) return true;
  const [shorter, longer] = a.length < b.length ? [a, b] : [b, a];
  if (longer.length !== shorter.length + 1) return false;
  for (let i = 1; i < longer.length; i++) {
    if (longer[i] === longer[i - 1] && longer.slice(0, i) + longer.slice(i + 1) === shorter) return true;
  }
  return false;
}

/** rare -> common, for rare words that are a safe misread of one clearly dominant common word. */
export function spellingFixes(counts, { rareMax = 3, commonMin = 30 } = {}) {
  const common = counts.filter((c) => c.n >= commonMin);
  const fixes = [];
  for (const rare of counts.filter((c) => c.n <= rareMax)) {
    const near = common.filter((c) => c.word !== rare.word && editDistance(rare.word, c.word) <= 2 && isSafeMisread(rare.word, c.word));
    if (!near.length) continue;
    near.sort((a, b) => b.n - a.n);
    if (near.length > 1 && near[0].n < 5 * near[1].n) continue;
    if (clusters(rare.word).length < 3) continue;
    fixes.push({ from: rare.word, to: near[0].word, n: rare.n, toN: near[0].n });
  }
  return fixes;
}

async function fix(db, dryRun) {
  const fixes = spellingFixes(await wordCounts(db));
  let rows = 0;
  for (const f of fixes) {
    console.log(`${f.from} (${f.n}) -> ${f.to} (${f.toN})`);
    if (!dryRun) {
      const result = await db.query('update public.rasipalan_archive set word = $1 where source = $2 and word = $3', [f.to, SOURCE, f.from]);
      rows += result.rowCount;
    }
  }
  console.log(`${fixes.length} misreads ${dryRun ? 'would be' : ''} fixed${dryRun ? '' : ` (${rows} rows updated)`}.`);
}

function loadDictionary() {
  if (!fs.existsSync(DICTIONARY)) return {};
  const text = fs.readFileSync(DICTIONARY, 'utf8');
  return JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1));
}

function saveDictionary(entries) {
  const header = [
    '/**',
    ' * English for the one-word rasi palan printed on Tamil daily calendar sheets,',
    ' * shown when the app language is English. Generated by',
    ' * scripts/maha-vocabulary.js --translate (Gemini), then reviewed; hand edits',
    ' * are kept when the script runs again. A word missing here falls back to the',
    ' * computed (Moon-transit) summary in English.',
    ' */',
  ].join('\n');
  fs.writeFileSync(DICTIONARY, `${header}\nexport default ${JSON.stringify(entries, null, 1)};\n`);
}

async function translateBatch(words) {
  const token = process.env.REPLICATE_API_TOKEN;
  const prompt = `These are one-word daily horoscope predictions (rasi palan) printed on Tamil daily calendars, e.g. வெற்றி, செலவு, நன்மை, எதிர்ப்பு.
Translate each into a short English word or phrase (1–3 words, capitalised, e.g. "Success", "Expenses", "Good fortune", "Opposition") as a reader of a horoscope would understand it. If a word looks like a misspelling, translate the intended word.
Reply with only a JSON object mapping each Tamil word exactly as given to its English.
Words: ${JSON.stringify(words)}`;
  let response;
  let prediction;
  for (let attempt = 0; attempt < 200; attempt++) {
    response = await fetch('https://api.replicate.com/v1/models/google/gemini-2.5-flash/predictions', {
      method: 'POST',
      headers: { authorization: `Bearer ${token}`, 'content-type': 'application/json', prefer: 'wait=60' },
      body: JSON.stringify({ input: { prompt, temperature: 0, thinking_budget: 0, max_output_tokens: 16000 } }),
    });
    prediction = await response.json();
    if (response.status !== 429) break;
    // Shares the 6-a-minute limit with any OCR run in progress.
    await new Promise((resolve) => setTimeout(resolve, ((prediction.retry_after || 10) + 2) * 1000));
  }
  for (let i = 0; i < 60 && ['starting', 'processing'].includes(prediction.status); i++) {
    await new Promise((resolve) => setTimeout(resolve, 2000));
    prediction = await (await fetch(prediction.urls.get, { headers: { authorization: `Bearer ${token}` } })).json();
  }
  if (prediction.status !== 'succeeded') throw new Error(`Replicate ${prediction.status}: ${prediction.error || JSON.stringify(prediction).slice(0, 200)}`);
  const text = Array.isArray(prediction.output) ? prediction.output.join('') : String(prediction.output);
  const out = {};
  for (const m of text.matchAll(/"([^"]+)"\s*:\s*"([^"]+)"/g)) out[m[1].trim()] = m[2].trim();
  return out;
}

async function translate(db, dryRun) {
  const dictionary = loadDictionary();
  const missing = (await wordCounts(db)).map((c) => c.word).filter((w) => !dictionary[w]);
  console.log(`${missing.length} words without English.`);
  for (let i = 0; i < missing.length; i += 150) {
    const batch = missing.slice(i, i + 150);
    const english = await translateBatch(batch);
    for (const w of batch) if (english[w]) dictionary[w] = english[w];
    if (!dryRun) saveDictionary(dictionary);
    console.log(`translated ${Math.min(i + 150, missing.length)}/${missing.length}`);
  }
  if (dryRun) console.log(JSON.stringify(dictionary, null, 1).slice(0, 2000));
  else saveDictionary(dictionary);
  console.log(`${Object.keys(dictionary).length} words in the dictionary.`);
}

const args = parseArgs();
const db = await connect();
try {
  if (args.fix) await fix(db, Boolean(args['dry-run']));
  if (args.translate) await translate(db, Boolean(args['dry-run']));
  if (!args.fix && !args.translate) console.log('Use --fix and/or --translate (with --dry-run to preview).');
} finally {
  await db.end();
}
